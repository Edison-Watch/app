#!/usr/bin/env node
// Writes (or removes) build/installer-telemetry.config.nsh, the switch for the
// Windows installer funnel telemetry (see build/installerTelemetry.nsh).
//
// Telemetry is OFF unless BOTH variables are set when this script runs:
//   SG_INSTALL_TELEMETRY_URL  PostHog capture endpoint, e.g. https://us.i.posthog.com/i/v0/e/
//                             (or a local mock such as http://127.0.0.1:8787/i/v0/e/)
//   SG_INSTALL_TELEMETRY_KEY  PostHog project key (phc_...)
// With either missing, the config file is deleted and makensis compiles the
// installer exactly as before (every telemetry macro expands to nothing).
//
// The file is generated rather than read from $%ENV% inside NSIS because
// electron-builder runs makensis with -WX, and an unset $%VAR% is a warning.
//
// Usage: node scripts/installer-telemetry-config.mjs [outFile]

import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const outFile = process.argv[2] ?? join(here, '..', 'build', 'installer-telemetry.config.nsh')

// Only characters that are safe inside an NSIS "..." string and a JSON string.
const SAFE = /^[A-Za-z0-9._~\-/]*$/

function fail(msg) {
  console.error(`[installer-telemetry] ${msg}`)
  process.exit(1)
}

const rawUrl = (process.env.SG_INSTALL_TELEMETRY_URL ?? '').trim()
const key = (process.env.SG_INSTALL_TELEMETRY_KEY ?? '').trim()

if (!rawUrl || !key) {
  if (existsSync(outFile)) rmSync(outFile)
  console.log('[installer-telemetry] disabled (SG_INSTALL_TELEMETRY_URL/KEY not set)')
  process.exit(0)
}

let url
try {
  url = new URL(rawUrl)
} catch {
  fail(`SG_INSTALL_TELEMETRY_URL is not a valid URL: ${rawUrl}`)
}
if (url.protocol !== 'https:' && url.protocol !== 'http:') fail('URL must be http(s)')
if (url.protocol === 'http:' && !['127.0.0.1', 'localhost'].includes(url.hostname)) {
  fail('plain http is only allowed for a local mock endpoint (127.0.0.1/localhost)')
}
if (url.search || url.hash || url.username || url.password) fail('URL must not carry query, hash or credentials')
if (!/^[A-Za-z0-9_-]+$/.test(key)) fail('SG_INSTALL_TELEMETRY_KEY has unexpected characters')
if (!SAFE.test(url.hostname) || !SAFE.test(url.pathname)) fail('URL has unexpected characters')

const secure = url.protocol === 'https:'
const port = url.port ? Number(url.port) : secure ? 443 : 80

const content = `; GENERATED by scripts/installer-telemetry-config.mjs - do not edit or commit.
!define SG_IT_ENABLED
!define SG_IT_HOST "${url.hostname}"
!define SG_IT_PORT ${port}
!define SG_IT_PATH "${url.pathname}"
!define SG_IT_SECURE ${secure ? 1 : 0}
!define SG_IT_KEY "${key}"
`
mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, content)
console.log(`[installer-telemetry] enabled -> ${url.protocol}//${url.hostname}:${port}${url.pathname}`)
